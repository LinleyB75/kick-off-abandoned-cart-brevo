// Writes docs/data-design.md: the table of values your developer sends, for the handoff.
// It is built from project.config.js, the MJML and data/params.json, so it cannot drift from what is really checked.
//   npm run data-design
const fs = require("fs");
const config = require("../project.config");
const { readTemplate } = require("../check-params");

const { used, optional } = readTemplate(fs.readFileSync(config.mjml, "utf8"));
const example = JSON.parse(fs.readFileSync("data/params.json", "utf8"));
const links = config.links || [];
const formats = config.formats || {};
const limits = config.maxLength || {};
const order = [...Object.keys(example), ...[...used].filter((n) => !(n in example))];

const rules = (name) => {
  if (links.includes(name)) return "An https address, no spaces, up to 2000 characters. No username or credential in it.";
  const max = limits[name] || limits.default || 200;
  return [`Text, up to ${max} characters.`, formats[name] ? `It ${formats[name].why}.` : ""].filter(Boolean).join(" ");
};
const cell = (s) => String(s).replace(/\|/g, "\\|");
const rows = order.map((n) => `| \`${n}\` | ${optional.has(n) ? "Optional" : "Required"} | ${cell((config.describe || {})[n] || "")} | ${cell(rules(n))} | \`${cell(example[n] ?? "")}\` |`);

const request = { to: [{ email: "customer@example.test", ...(example.firstName ? { name: example.firstName } : {}) }], templateId: 12, params: example };
const md = `# Data design: ${config.name}

The values your application sends to Brevo with the email. This table is generated by \`npm run data-design\` from the settings file and the email itself, and the same rules are checked before anything is sent.

## The values

| Value | Required | What it is | Rules | Example |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Rules for every value

- Every value is sent as text, including numbers.
- No text value may contain \`<\` or \`>\`, or Brevo tags such as \`{{\` or \`{%\`, so a value can never change the email. The two addresses have their own rules, above.
${(config.never || []).map((r) => `- No text value may contain anything that ${r.why}.`).join("\n")}
- The whole \`params\` object must stay under 100 KB, which is Brevo's limit.
- Leaving an optional value out, or sending it empty, is fine. The email still reads correctly.

## The request

\`templateId\` is the ID of the email in your Brevo account. The values below are made up.

\`\`\`json
${JSON.stringify(request, null, 2)}
\`\`\`

\`npm run send:dry\` prints this request and sends nothing. \`npm run send:sandbox\` checks it with Brevo and sends nothing.
`;
fs.mkdirSync("docs", { recursive: true });
fs.writeFileSync("docs/data-design.md", md);
console.log(`Wrote docs/data-design.md (${order.length} values, ${[...optional].length} optional).`);